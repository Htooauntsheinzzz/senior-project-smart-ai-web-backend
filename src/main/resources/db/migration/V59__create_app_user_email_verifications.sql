-- Spec file 60: the pending email verification of a form registration.
-- A row exists only while a verification link is waiting to be used: it is replaced when a new link is sent and
-- deleted when the email is verified (app_users.email_verified_at then holds the result). At most one row per user.
-- Only the SHA-256 hash of the token is stored; the token itself exists only in the email.
-- No cascade, as everywhere in this schema.
CREATE TABLE app_user_email_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_app_user_email_verifications_user
        UNIQUE (user_id),

    CONSTRAINT uk_app_user_email_verifications_token_hash
        UNIQUE (token_hash),

    CONSTRAINT fk_app_user_email_verifications_user
        FOREIGN KEY (user_id)
        REFERENCES app_users(id),

    CONSTRAINT chk_app_user_email_verifications_expiry
        CHECK (expires_at > created_at)
);
