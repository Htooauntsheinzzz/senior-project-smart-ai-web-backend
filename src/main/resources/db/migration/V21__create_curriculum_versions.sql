CREATE TABLE curriculum_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id BIGINT NOT NULL,
    version_code VARCHAR(50) NOT NULL,
    version_name VARCHAR(200) NOT NULL,
    academic_year_label VARCHAR(20) NOT NULL,
    description TEXT,
    effective_from DATE,
    effective_to DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP,

    CONSTRAINT fk_curriculum_versions_program
        FOREIGN KEY (program_id) REFERENCES programs(id),

    CONSTRAINT fk_curriculum_versions_created_by
        FOREIGN KEY (created_by) REFERENCES app_users(id),

    CONSTRAINT fk_curriculum_versions_updated_by
        FOREIGN KEY (updated_by) REFERENCES app_users(id),

    CONSTRAINT uk_curriculum_versions_program_code
        UNIQUE (program_id, version_code),

    CONSTRAINT chk_curriculum_versions_status
        CHECK (status IN ('ACTIVE', 'ARCHIVED')),

    CONSTRAINT chk_curriculum_versions_dates
        CHECK (
            effective_to IS NULL
            OR effective_from IS NULL
            OR effective_to >= effective_from
        )
);

-- Initial policy: at most one live ACTIVE curriculum version per program.
CREATE UNIQUE INDEX uk_curriculum_versions_one_active
ON curriculum_versions(program_id)
WHERE status = 'ACTIVE' AND is_deleted = FALSE;

CREATE INDEX idx_curriculum_versions_program
ON curriculum_versions(program_id);
