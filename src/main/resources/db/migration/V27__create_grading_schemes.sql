-- No scheme is seeded: rows must come from the university's approved grading policy.
-- repeat_attempt_policy stays NULL until the official retake rule is known; while it is NULL a student
-- with repeated courses under this scheme gets no CGPA or earned-credit total.
CREATE TABLE grading_schemes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_code VARCHAR(50) NOT NULL,
    scheme_name VARCHAR(150) NOT NULL,
    description TEXT,
    repeat_attempt_policy VARCHAR(30),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_grading_schemes_scheme_code UNIQUE (scheme_code),
    CONSTRAINT chk_grading_schemes_repeat_attempt_policy
        CHECK (repeat_attempt_policy IS NULL
            OR repeat_attempt_policy IN ('ALL_ATTEMPTS', 'LATEST_ATTEMPT', 'BEST_ATTEMPT'))
);
