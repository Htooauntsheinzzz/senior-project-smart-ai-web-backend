-- course_sections.schedule stays as it is; legacy strings are not parsed into rows.
-- room_id has no foreign key because no rooms table exists yet; room_label is the room text until one does.
CREATE TABLE course_section_meetings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_section_id BIGINT NOT NULL,
    meeting_type VARCHAR(30) NOT NULL,
    day_of_week SMALLINT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE NOT NULL,
    room_id BIGINT,
    room_label VARCHAR(150),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,

    CONSTRAINT chk_course_section_meetings_type CHECK (meeting_type IN ('LECTURE', 'LAB', 'TUTORIAL')),
    CONSTRAINT chk_course_section_meetings_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT chk_course_section_meetings_time CHECK (end_time > start_time),
    CONSTRAINT chk_course_section_meetings_dates CHECK (effective_to >= effective_from),
    CONSTRAINT fk_course_section_meetings_section
        FOREIGN KEY (course_section_id) REFERENCES course_sections(id)
);

CREATE INDEX idx_course_section_meetings_section
    ON course_section_meetings (course_section_id, is_active, is_deleted);
