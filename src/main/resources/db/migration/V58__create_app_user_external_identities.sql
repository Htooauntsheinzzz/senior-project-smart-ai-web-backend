-- Spec file 60: the link between an Admin web user and an account at an external sign-in provider (Google).
-- One row per (user, provider). The provider's stable subject id is the key that identifies the person at the
-- provider; the email, name and status are NOT copied here, they are read from app_users (no repeated data).
-- No cascade, as everywhere in this schema.
CREATE TABLE app_user_external_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    provider VARCHAR(30) NOT NULL,
    -- The "sub" claim of the provider's ID token. It never changes, unlike an email address.
    provider_subject VARCHAR(255) NOT NULL,
    linked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- One external account signs in as exactly one user.
    CONSTRAINT uk_app_user_external_identities_provider_subject
        UNIQUE (provider, provider_subject),

    -- One user has at most one account per provider.
    CONSTRAINT uk_app_user_external_identities_user_provider
        UNIQUE (user_id, provider),

    CONSTRAINT fk_app_user_external_identities_user
        FOREIGN KEY (user_id)
        REFERENCES app_users(id),

    CONSTRAINT chk_app_user_external_identities_provider
        CHECK (provider IN ('GOOGLE'))
);
