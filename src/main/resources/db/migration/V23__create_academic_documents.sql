CREATE TABLE academic_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    category_id BIGINT NOT NULL,
    academic_year_label VARCHAR(20) NOT NULL,
    curriculum_version_id BIGINT,
    program_id BIGINT,
    department_id BIGINT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT REFERENCES app_users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT REFERENCES app_users(id),
    updated_at TIMESTAMP,

    CONSTRAINT fk_academic_documents_category
        FOREIGN KEY (category_id)
        REFERENCES document_categories(id),

    CONSTRAINT fk_academic_documents_curriculum
        FOREIGN KEY (curriculum_version_id)
        REFERENCES curriculum_versions(id),

    CONSTRAINT fk_academic_documents_program
        FOREIGN KEY (program_id)
        REFERENCES programs(id),

    CONSTRAINT fk_academic_documents_department
        FOREIGN KEY (department_id)
        REFERENCES departments(id),

    -- One scope reference at most; all NULL means the document is university-wide.
    CONSTRAINT chk_academic_documents_scope
        CHECK (
            (
                CASE WHEN curriculum_version_id IS NOT NULL THEN 1 ELSE 0 END
              + CASE WHEN program_id IS NOT NULL THEN 1 ELSE 0 END
              + CASE WHEN department_id IS NOT NULL THEN 1 ELSE 0 END
            ) <= 1
        )
);

CREATE INDEX idx_academic_documents_category
ON academic_documents(category_id);

CREATE INDEX idx_academic_documents_curriculum
ON academic_documents(curriculum_version_id);

CREATE INDEX idx_academic_documents_program
ON academic_documents(program_id);

CREATE INDEX idx_academic_documents_department
ON academic_documents(department_id);

CREATE INDEX idx_academic_documents_year
ON academic_documents(academic_year_label);

CREATE INDEX idx_academic_documents_active
ON academic_documents(is_active, is_deleted);
