-- room_id has no foreign key because no rooms table exists yet; room_label is the room text until one does.
CREATE TABLE course_exams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_section_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    exam_type VARCHAR(20) NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL,
    room_id BIGINT,
    room_label VARCHAR(150),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP,

    CONSTRAINT chk_course_exams_type CHECK (exam_type IN ('QUIZ', 'MIDTERM', 'FINAL', 'PRACTICAL')),
    CONSTRAINT chk_course_exams_status CHECK (status IN ('DRAFT', 'SCHEDULED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT chk_course_exams_time CHECK (ends_at > starts_at),
    CONSTRAINT fk_course_exams_section
        FOREIGN KEY (course_section_id) REFERENCES course_sections(id),
    CONSTRAINT fk_course_exams_created_by
        FOREIGN KEY (created_by) REFERENCES app_users(id),
    CONSTRAINT fk_course_exams_updated_by
        FOREIGN KEY (updated_by) REFERENCES app_users(id)
);

CREATE INDEX idx_course_exams_upcoming
    ON course_exams (course_section_id, status, is_deleted, starts_at);
