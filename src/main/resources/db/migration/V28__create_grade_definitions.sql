CREATE TABLE grade_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grading_scheme_id BIGINT NOT NULL,
    grade_code VARCHAR(20) NOT NULL,
    grade_point NUMERIC(4,2),
    counts_in_gpa BOOLEAN NOT NULL,
    earns_credit BOOLEAN NOT NULL,
    is_passing BOOLEAN NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_grade_definitions_scheme_grade UNIQUE (grading_scheme_id, grade_code),
    CONSTRAINT chk_grade_definitions_grade_point
        CHECK (grade_point IS NULL OR grade_point >= 0),
    CONSTRAINT chk_grade_definitions_gpa_needs_point
        CHECK (counts_in_gpa = FALSE OR grade_point IS NOT NULL),
    CONSTRAINT chk_grade_definitions_credit_needs_pass
        CHECK (earns_credit = FALSE OR is_passing = TRUE),
    CONSTRAINT fk_grade_definitions_scheme
        FOREIGN KEY (grading_scheme_id) REFERENCES grading_schemes(id)
);

CREATE INDEX idx_grade_definitions_scheme_id ON grade_definitions (grading_scheme_id);
