-- Step 17 (spec file 58): the messages of a conversation, two per completed turn (USER, then ASSISTANT). The order within
-- a conversation is the order of id. content is the Student's message or the final answer the Student received; tool
-- calls, tool results, document passages and prompts are never stored.
CREATE TABLE assistant_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL,
    role VARCHAR(20) NOT NULL,
    content TEXT NOT NULL,
    request_id VARCHAR(36),
    model VARCHAR(100),
    -- ASSISTANT only: the sources array of the chat response as JSON, NULL when the answer used no document.
    sources TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_assistant_messages_conversation
        FOREIGN KEY (conversation_id)
        REFERENCES assistant_conversations(id),

    CONSTRAINT chk_assistant_messages_role
        CHECK (role IN ('USER', 'ASSISTANT'))
);

CREATE INDEX idx_assistant_messages_conversation
ON assistant_messages (conversation_id, id);
