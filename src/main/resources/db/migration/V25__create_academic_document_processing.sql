-- One processing record per file revision; READY only after the ingestion pipeline finishes.
CREATE TABLE academic_document_processing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id BIGINT NOT NULL UNIQUE,
    status VARCHAR(30) NOT NULL DEFAULT 'UPLOADED',
    attempt_count INTEGER NOT NULL DEFAULT 0,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    last_error_code VARCHAR(100),
    last_error_message VARCHAR(500),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_academic_document_processing_file
        FOREIGN KEY (file_id)
        REFERENCES academic_document_files(id),

    CONSTRAINT chk_academic_document_processing_status
        CHECK (
            status IN (
                'UPLOADED',
                'QUEUED',
                'PROCESSING',
                'CHUNKING',
                'EMBEDDING',
                'READY',
                'FAILED'
            )
        ),

    CONSTRAINT chk_academic_document_processing_attempts
        CHECK (attempt_count >= 0)
);

CREATE INDEX idx_academic_document_processing_status
ON academic_document_processing(status);
