CREATE TABLE student_course_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id BIGINT NOT NULL,
    grade_definition_id BIGINT NOT NULL,
    credits_attempted NUMERIC(5,2) NOT NULL,
    result_status VARCHAR(20) NOT NULL,
    finalized_at TIMESTAMP,
    finalized_by BIGINT,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT,
    updated_at TIMESTAMP,

    CONSTRAINT uk_student_course_results_enrollment UNIQUE (enrollment_id),
    CONSTRAINT chk_student_course_results_credits CHECK (credits_attempted >= 0),
    CONSTRAINT chk_student_course_results_status CHECK (result_status IN ('DRAFT', 'FINALIZED')),
    CONSTRAINT chk_student_course_results_finalized
        CHECK (result_status <> 'FINALIZED' OR (finalized_at IS NOT NULL AND finalized_by IS NOT NULL)),
    CONSTRAINT fk_student_course_results_enrollment
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id),
    CONSTRAINT fk_student_course_results_grade
        FOREIGN KEY (grade_definition_id) REFERENCES grade_definitions(id),
    CONSTRAINT fk_student_course_results_finalized_by
        FOREIGN KEY (finalized_by) REFERENCES app_users(id),
    CONSTRAINT fk_student_course_results_created_by
        FOREIGN KEY (created_by) REFERENCES app_users(id),
    CONSTRAINT fk_student_course_results_updated_by
        FOREIGN KEY (updated_by) REFERENCES app_users(id)
);

CREATE INDEX idx_student_course_results_grade ON student_course_results (grade_definition_id);
CREATE INDEX idx_student_course_results_status ON student_course_results (result_status);

-- Append-only history of every grade change: who, when, previous value, new value and the correction reason.
CREATE TABLE student_course_result_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_course_result_id BIGINT NOT NULL,
    action VARCHAR(20) NOT NULL,
    previous_grade_definition_id BIGINT,
    new_grade_definition_id BIGINT NOT NULL,
    previous_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    credits_attempted NUMERIC(5,2) NOT NULL,
    reason VARCHAR(500),
    changed_by BIGINT NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_student_course_result_audits_action
        CHECK (action IN ('CREATED', 'UPDATED', 'FINALIZED', 'CORRECTED')),
    CONSTRAINT fk_student_course_result_audits_result
        FOREIGN KEY (student_course_result_id) REFERENCES student_course_results(id),
    CONSTRAINT fk_student_course_result_audits_previous_grade
        FOREIGN KEY (previous_grade_definition_id) REFERENCES grade_definitions(id),
    CONSTRAINT fk_student_course_result_audits_new_grade
        FOREIGN KEY (new_grade_definition_id) REFERENCES grade_definitions(id),
    CONSTRAINT fk_student_course_result_audits_changed_by
        FOREIGN KEY (changed_by) REFERENCES app_users(id)
);

CREATE INDEX idx_student_course_result_audits_result ON student_course_result_audits (student_course_result_id);
