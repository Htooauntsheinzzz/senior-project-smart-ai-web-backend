-- File metadata only: the bytes live in protected storage under a backend-generated storage_key.
CREATE TABLE academic_document_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    revision_number INTEGER NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    storage_key VARCHAR(600) NOT NULL UNIQUE,
    mime_type VARCHAR(150) NOT NULL,
    file_extension VARCHAR(12) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256_checksum CHAR(64) NOT NULL,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    uploaded_by BIGINT NOT NULL,
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_academic_document_files_document
        FOREIGN KEY (document_id)
        REFERENCES academic_documents(id),

    CONSTRAINT fk_academic_document_files_uploaded_by
        FOREIGN KEY (uploaded_by)
        REFERENCES app_users(id),

    CONSTRAINT uk_academic_document_files_revision
        UNIQUE (document_id, revision_number),

    CONSTRAINT chk_academic_document_files_revision
        CHECK (revision_number > 0),

    CONSTRAINT chk_academic_document_files_size
        CHECK (size_bytes > 0)
);

CREATE UNIQUE INDEX uk_academic_document_files_one_current
ON academic_document_files(document_id)
WHERE is_current = TRUE;

CREATE INDEX idx_academic_document_files_document
ON academic_document_files(document_id);
