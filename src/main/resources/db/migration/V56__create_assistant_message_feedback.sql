-- Spec file 59: a Student's rating of one assistant answer, reviewed by Admins on the AI Feedback screen.
-- One row per answer (message_id is unique): rating it again replaces the rating and reopens the review.
-- No cascade, as everywhere in this schema: the application deletes the feedback of a conversation before its messages,
-- so a deleted conversation leaves no feedback behind.
CREATE TABLE assistant_message_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The rated ASSISTANT message.
    message_id BIGINT NOT NULL,
    conversation_id UUID NOT NULL,
    student_id BIGINT NOT NULL,
    rating VARCHAR(20) NOT NULL,
    comment VARCHAR(1000),
    review_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    review_note VARCHAR(1000),
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- The time of the Student's latest rating or comment.
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_assistant_message_feedback_message UNIQUE (message_id),

    CONSTRAINT fk_assistant_message_feedback_message
        FOREIGN KEY (message_id)
        REFERENCES assistant_messages(id),

    CONSTRAINT fk_assistant_message_feedback_conversation
        FOREIGN KEY (conversation_id)
        REFERENCES assistant_conversations(id),

    CONSTRAINT fk_assistant_message_feedback_student
        FOREIGN KEY (student_id)
        REFERENCES students(id),

    CONSTRAINT fk_assistant_message_feedback_reviewer
        FOREIGN KEY (reviewed_by)
        REFERENCES app_users(id),

    CONSTRAINT chk_assistant_message_feedback_rating
        CHECK (rating IN ('POSITIVE', 'NEGATIVE')),

    CONSTRAINT chk_assistant_message_feedback_review_status
        CHECK (review_status IN ('PENDING', 'REVIEWED', 'RESOLVED'))
);

-- The Admin list, newest submission first.
CREATE INDEX idx_assistant_message_feedback_submitted
ON assistant_message_feedback (submitted_at DESC, id DESC);

-- Deleting the feedback of a conversation, and its join to the conversation.
CREATE INDEX idx_assistant_message_feedback_conversation
ON assistant_message_feedback (conversation_id);

-- The Admin conversation list orders every Student's conversations by latest activity.
CREATE INDEX idx_assistant_conversations_updated
ON assistant_conversations (updated_at DESC, id DESC);
